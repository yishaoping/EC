/**
 * @file    gth_init.c
 * @brief   Guardian Heart Table（GHT）过滤与调度配置
 *
 * @details r_ini() 告诉 GuardianCouncil 哪类 BOOM 提交事件需要形成检查包，
 *          每类事件应从 LDQ、STQ、PRF 等哪条数据路径取值，以及检查窗口
 *          应被路由到哪个 checker/SE。它配置的是测试基础设施，不产生
 *          负载；实际事件由 test_workload.c 在监控窗口内触发。
 */

#include <stdio.h>
#include "rocc.h"
#include "spin_lock.h"
#include "ght.h"
#include "gth_init.h"
#include "clint.h"

/**
 * @brief  配置 GHT 指令过滤器、SE 调度范围和 checker 路由。
 * @param  num_checkers  checker 核数量
 * @return 0；该接口当前不报告硬件配置错误。
 *
 * @details 配置内容包括：
 *          【Load 指令过滤器（GID=0x01）】
 *          - 标准 load:   lb/lh/lw/lbu/lhu/ld/lwu (opcode=0x03, sel_d=0x02 LDQ)
 *          - 浮点 load:   flw/fld/flq (opcode=0x07)
 *          - 压缩 load:   c.flw/c.fld/c.lw/c.ld 等 (RVC 指令)
 *
 *          【Store 指令过滤器 (GID=0x02)】
 *          - 标准 store:  sb/sh/sw/sd (opcode=0x23, sel_d=0x03 STQ)
 *          - 浮点 store:  fsw/fsd/fsq (opcode=0x27)
 *          - 压缩 store:  c.fsw/c.fsd/c.sw/c.sd 等 (RVC 指令)
 *
 *          【CSR 读指令过滤器 (GID=0x03)】
 *          - csrrw/csrrs/csrrc/csrrwi/csrrsi/csrrci (opcode=0x73, sel_d=0x01 PRFs)
 *
 *          【Atomic 指令过滤器（GID=0x01）】
 *          - 32位原子: funct=0x02, 64位原子: funct=0x03 (opcode=0x2F, sel_d=0x05)
 *
 *          【SE 调度配置】
 *          - SE0..SE3 分别绑定 checker hart 1..4
 *          - policy=0x01 使用硬件定义的轮询策略
 *
 * @note   配置表包含 RVC load/store，尽管 compile.sh 当前 march 未启用 C；
 *         这些项为硬件接口的完整性和将来的压缩指令负载保留。
 */
int r_ini(int num_checkers)
{
    // 先设置参与调度的 checker 数量，后续 SE/mapper 配置依赖该拓扑。
    ght_set_numberofcheckers(num_checkers);

    // ========== Load 指令过滤器 (GID=0x01, sel_d=0x02=LDQ) ==========
    ght_cfg_filter(0x01, 0x00, 0x03, 0x02);     // lb   (funct=0x00)
    ght_cfg_filter(0x01, 0x01, 0x03, 0x02);     // lh   (funct=0x01)
    ght_cfg_filter(0x01, 0x02, 0x03, 0x02);     // lw   (funct=0x02)
    ght_cfg_filter(0x01, 0x04, 0x03, 0x02);     // lbu  (funct=0x04)
    ght_cfg_filter(0x01, 0x05, 0x03, 0x02);     // lhu  (funct=0x05)
    ght_cfg_filter(0x01, 0x03, 0x03, 0x02);     // ld   (funct=0x03)
    ght_cfg_filter(0x01, 0x06, 0x03, 0x02);     // lwu  (funct=0x06)

    // 浮点 load 指令
    ght_cfg_filter(0x01, 0x02, 0x07, 0x02);     // flw  (funct=0x02)
    ght_cfg_filter(0x01, 0x03, 0x07, 0x02);     // fld  (funct=0x03)
    ght_cfg_filter(0x01, 0x04, 0x07, 0x02);     // flq  (funct=0x04)

    // 压缩 load 指令 (RVC, opcode=0x00, MSB=0)
    ght_cfg_filter_rvc(0x01, 0x02, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x03, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x04, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x05, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x06, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x07, 0x00, 0x00, 0x02);

    // 压缩 load 指令 (RVC, opcode=0x02, MSB=0)
    ght_cfg_filter_rvc(0x01, 0x02, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x03, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x04, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x05, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x06, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x07, 0x02, 0x00, 0x02);

    // ========== Store 指令过滤器 (GID=0x02, sel_d=0x03=STQ) ==========
    ght_cfg_filter(0x02, 0x00, 0x23, 0x03);     // sb   (funct=0x00)
    ght_cfg_filter(0x02, 0x01, 0x23, 0x03);     // sh   (funct=0x01)
    ght_cfg_filter(0x02, 0x02, 0x23, 0x03);     // sw   (funct=0x02)
    ght_cfg_filter(0x02, 0x03, 0x23, 0x03);     // sd   (funct=0x03)

    // 浮点 store 指令
    ght_cfg_filter(0x02, 0x02, 0x27, 0x03);     // fsw  (funct=0x02)
    ght_cfg_filter(0x02, 0x03, 0x27, 0x03);     // fsd  (funct=0x03)
    ght_cfg_filter(0x02, 0x04, 0x27, 0x03);     // fsq  (funct=0x04)

    // 压缩 store 指令 (RVC, opcode=0x00, MSB=1)
    ght_cfg_filter_rvc(0x02, 0x02, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x03, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x04, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x05, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x06, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x07, 0x00, 0x01, 0x03);

    // 压缩 store 指令 (RVC, opcode=0x02, MSB=1)
    ght_cfg_filter_rvc(0x02, 0x02, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x03, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x04, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x05, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x06, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x07, 0x02, 0x01, 0x03);

    // ========== CSR 读指令过滤器 (GID=0x03, sel_d=0x01=PRFs) ==========
    ght_cfg_filter(0x03, 0x01, 0x73, 0x01);     // csrrw  (funct=0x01)
    ght_cfg_filter(0x03, 0x02, 0x73, 0x01);     // csrrs  (funct=0x02)
    ght_cfg_filter(0x03, 0x03, 0x73, 0x01);     // csrrc  (funct=0x03)
    ght_cfg_filter(0x03, 0x05, 0x73, 0x01);     // csrrwi (funct=0x05)
    ght_cfg_filter(0x03, 0x06, 0x73, 0x01);     // csrrsi (funct=0x06)
    ght_cfg_filter(0x03, 0x07, 0x73, 0x01);     // csrrci (funct=0x07)

    // ========== Atomic 指令过滤器 (GID=0x01, sel_d=0x05=STQ+PRFs) ==========
    ght_cfg_filter(0x01, 0x02, 0x2F, 0x05);     // 32位原子操作
    ght_cfg_filter(0x01, 0x03, 0x2F, 0x05);     // 64位原子操作

    // ========== SE 执行单元调度配置 (policy=0x01=轮询RR) ==========
    ght_cfg_se(0x00, 0x01, 0x01, 0x01);         // SE0: 核心 1→1
    ght_cfg_se(0x01, 0x02, 0x01, 0x02);         // SE1: 核心 2→2
    ght_cfg_se(0x02, 0x03, 0x01, 0x03);         // SE2: 核心 3→3
    ght_cfg_se(0x03, 0x04, 0x01, 0x04);         // SE3: 核心 4→4

    // 将每个 checker 的普通事件包和上下文快照路由到对应 SE 位。
    for (int i = 1; i <= num_checkers; i++) {
        r_set_corex_p_s(i);
    }

    // width=0 关闭额外调试宽度限制，保留完整检查数据。
    ght_debug_filter_width(0);
    lock_acquire(&uart_lock);
    printf("R: Initialisation is completed!\r\n");
    lock_release(&uart_lock);

    return 0;
}
