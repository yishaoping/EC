#include "init.h"

#include <stdint.h>
#include <stdio.h>

#include "../hw/ghe.h"
#include "../hw/ght.h"
#include "../hw/spin_lock.h"
#include "config.h"

void r_ini(int num_checkers)
{
    /* 配置 checker 数量、指令过滤器、同步段和 checker 映射关系。 */
    ght_set_numberofcheckers(num_checkers);

    ght_cfg_filter(0x01, 0x00, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x01, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x02, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x04, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x05, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x03, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x06, 0x03, 0x02);
    ght_cfg_filter(0x01, 0x02, 0x07, 0x02);
    ght_cfg_filter(0x01, 0x03, 0x07, 0x02);
    ght_cfg_filter(0x01, 0x04, 0x07, 0x02);

    ght_cfg_filter_rvc(0x01, 0x02, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x03, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x04, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x05, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x06, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x07, 0x00, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x02, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x03, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x04, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x05, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x06, 0x02, 0x00, 0x02);
    ght_cfg_filter_rvc(0x01, 0x07, 0x02, 0x00, 0x02);

    ght_cfg_filter(0x02, 0x00, 0x23, 0x03);
    ght_cfg_filter(0x02, 0x01, 0x23, 0x03);
    ght_cfg_filter(0x02, 0x02, 0x23, 0x03);
    ght_cfg_filter(0x02, 0x03, 0x23, 0x03);
    ght_cfg_filter(0x02, 0x02, 0x27, 0x03);
    ght_cfg_filter(0x02, 0x03, 0x27, 0x03);
    ght_cfg_filter(0x02, 0x04, 0x27, 0x03);

    ght_cfg_filter_rvc(0x02, 0x02, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x03, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x04, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x05, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x06, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x07, 0x00, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x02, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x03, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x04, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x05, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x06, 0x02, 0x01, 0x03);
    ght_cfg_filter_rvc(0x02, 0x07, 0x02, 0x01, 0x03);

    ght_cfg_filter(0x03, 0x01, 0x73, 0x01);
    ght_cfg_filter(0x03, 0x02, 0x73, 0x01);
    ght_cfg_filter(0x03, 0x03, 0x73, 0x01);
    ght_cfg_filter(0x03, 0x05, 0x73, 0x01);
    ght_cfg_filter(0x03, 0x06, 0x73, 0x01);
    ght_cfg_filter(0x03, 0x07, 0x73, 0x01);

    ght_cfg_filter(0x01, 0x02, 0x2F, 0x05);
    ght_cfg_filter(0x01, 0x03, 0x2F, 0x05);

    ght_cfg_se(0x00, 0x01, 0x01, 0x01);
    ght_cfg_se(0x01, 0x02, 0x01, 0x02);
    ght_cfg_se(0x02, 0x03, 0x01, 0x03);
    ght_cfg_se(0x03, 0x04, 0x01, 0x04);

    for (int i = 1; i <= NUM_CHECKERS; i++) {
        r_set_corex_p_s(i);
    }

    ght_debug_filter_width(0);
    ghe_set_checker_mask(0xF);
    uint64_t rd_mask = ghe_get_checker_mask();

    lock_acquire(&uart_lock);
    printf("R: Checker mask set to 0x%lx\r\n", rd_mask);
    lock_release(&uart_lock);

    lock_acquire(&uart_lock);
    printf("R: Initialisation is completed!\r\n");
    lock_release(&uart_lock);
}
